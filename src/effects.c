static sint32 effects_advance_tex_cb(CB_NODE *node)
{
    // Callback storage carries a checked index into native animation owners
    uint32 idx = node->arg.idx;
    EFFECT_TEX_ANIM *anim;

    FUNCTION_MARKER(0x80040C6C, "MAIN.EXE");
    if (idx >= 14)
        abort();
    anim = &effects_tex_anims[idx];
    anim->timer = anim->timer - (race_cfg.players == 2 ? 2u : 1u);
    if (anim->timer >= 0)
        return anim->timer;
    anim->timer = anim->timer + anim->period;
    while (anim->timer < 0)
    {
        anim->idx = (anim->idx + 1) % anim->count;
        anim->timer = anim->timer + anim->period;
    }
    if ((uint32)anim->idx >= (uint32)anim->count)
        abort();
    PSX_RECT rect = anim->frames[anim->idx];
    MoveImage(&rect, anim->x, anim->y);
    anim->idx = (anim->idx + 1) % anim->count;
    return anim->idx;
}

