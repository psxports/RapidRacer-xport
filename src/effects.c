static void effects_mat_identity(MATRIX *dst)
{
    memset(dst->m, 0, sizeof(dst->m));
    dst->m[0][0] = dst->m[1][1] = dst->m[2][2] = ONE;
    dst->t[0] = dst->t[1] = dst->t[2] = 0;
}

static void effects_load_models(void)
{
    static const uint32 offsets[4] = {5608, 4456, 2504, 0};
    static const uint32 sizes[4] = {3856, 1152, 1952, 2504};
    MESH_MODEL models[4] = {0};
    uint32 idx;

    if (effects_models_ready)
        return;
    for (idx = 0; idx < 4; ++idx)
    {
        if (!mesh_decode_model(effects_model_data + offsets[idx], sizes[idx], &models[idx]))
        {
            uint32 clear_idx;
            for (clear_idx = 0; clear_idx < 4; ++clear_idx)
                mesh_clear_model(&models[clear_idx]);
            abort();
        }
    }
    memcpy(effects_models, models, sizeof(models));
    effects_models_ready = 1;
}

