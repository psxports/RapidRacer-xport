static void effects_render_particles(uint32 *ot)
{
    uint32 packet_offset = render_packet_offset();
    POLY_FT4 *poly;
    sint32 double_height = race_cfg.players != 2;
    MATRIX saved;
    MATRIX identity;
    sint32 idx;

    FUNCTION_MARKER(0x8004158C, "MAIN.EXE");
    ReadRotMatrix(&saved);
    SetLightMatrix(&saved);
    gte_set_back_color_raw(saved.t[0], saved.t[1], saved.t[2]);
    memset(&identity, 0, sizeof(identity));
    identity.m[0][0] = ONE;
    identity.m[1][1] = ONE;
    identity.m[2][2] = ONE;
    SetRotMatrix(&identity);
    SetTransMatrix(&identity);
    for (idx = 0; idx < EFFECT_PARTICLE_COUNT; ++idx)
    {
        const EFFECT_PARTICLE *particle = &effects_emitter.particles[idx];
        sint16 kind = particle->kind;
        if (kind != 0)
        {
            SVECTOR src;
            VECTOR t;
            SVECTOR corners[4];
            sint32 scr[4];
            sint32 depth[4];
            sint32 flags;
            sint32 combined_flags;
            sint32 horizontal = particle->size;
            sint32 vertical = horizontal;
            sint32 avg;
            uint32 *bucket;

            if (double_height != 0)
                vertical = (sint16)(vertical * 2);
            src.vx = particle->pos[0];
            src.vy = particle->pos[1];
            src.vz = particle->pos[2];
            src.pad = kind;
            gte_transform_light(&src, &t, &flags);
            if (flags < 0)
                continue;
            corners[0].vx = t.vx - horizontal;
            corners[0].vy = t.vy - vertical;
            corners[0].vz = t.vz;
            corners[0].pad = 0;
            corners[1].vx = t.vx + horizontal;
            corners[1].vy = corners[0].vy;
            corners[1].vz = corners[0].vz;
            corners[1].pad = 0;
            corners[2].vx = corners[0].vx;
            corners[2].vy = t.vy;
            corners[2].vz = corners[0].vz;
            corners[2].pad = 0;
            corners[3].vx = corners[1].vx;
            corners[3].vy = corners[2].vy;
            corners[3].vz = corners[0].vz;
            corners[3].pad = 0;
            combined_flags = 0;
            depth[0] = gte_project_full_depth(&corners[0], &scr[0], &flags);
            combined_flags |= flags;
            depth[1] = gte_project_full_depth(&corners[1], &scr[1], &flags);
            combined_flags |= flags;
            depth[2] = gte_project_full_depth(&corners[2], &scr[2], &flags);
            combined_flags |= flags;
            if (combined_flags < 0)
                continue;
            poly = render_packet_at(packet_offset, sizeof(*poly));
            poly->p[0].xy.xy = scr[0];
            poly->p[1].xy.xy = scr[1];
            poly->p[2].xy.xy = scr[2];
            NormalClip(scr[0], scr[1], scr[2]);
            avg = AverageZ3(depth[0], depth[1], depth[2]);
            avg--;
            if ((uint32)avg >= 3200)
                continue;
            gte_project_full_depth(&corners[3], &scr[3], &flags);
            if (flags < 0)
                continue;
            bucket = ot + ((uint32)avg >> 5);
            poly->p[3].xy.xy = scr[3];
            poly->rgbc.rgbc = 0x2C808080;
            poly->p[0].uv.uv = effects_emitter.uv[0];
            poly->p[0].attr = effects_emitter.uv[0] >> 16;
            poly->p[1].uv.uv = effects_emitter.uv[1];
            poly->p[1].attr = effects_emitter.uv[1] >> 16;
            poly->p[2].uv.uv = effects_emitter.uv[2];
            poly->p[3].uv.uv = effects_emitter.uv[3];
            if (kind == 2)
                poly->p[0].attr = effects_emitter.uv[2] >> 16;
            else if (kind == 3)
                poly->p[0].attr = effects_emitter.uv[3] >> 16;
            poly->tag = *bucket;
            setlen(poly, getlen(poly) | 9);
            AddPrim(bucket, poly);
            packet_offset += sizeof(*poly);
        }
    }
    SetRotMatrix(&saved);
    SetTransMatrix(&saved);
    render_packet_publish(packet_offset);
}

static void effects_create_particle(EFFECT_EMITTER *emitter, uint32 idx)
{
    EFFECT_PARTICLE *particle = &emitter->particles[idx];
    sint32 random = random_next();
    sint32 factor;
    sint32 distance;
    sint32 scale;
    SVECTOR input;
    VECTOR output;

    particle->kind = random % 3 + 1;
    random = random_next();
    particle->size = random % 50 + 50;
    factor = random_next() & 0x0FFF;
    gte_intpl12(&emitter->origin[1], &emitter->origin[0], factor, &output);
    particle->pos[0] = output.vx;
    particle->pos[1] = output.vy;
    particle->pos[2] = output.vz;
    distance = 2048 - factor;
    factor = 2048 - distance / 2;
    gte_intpl12(&emitter->dir[1], &emitter->dir[0], factor, &output);
    distance = abs(distance);
    scale = sra((2048u - distance / 2) * emitter->speed, 11u);
    random = random_next();
    factor = random % scale + scale + emitter->speed;
    input.vx = output.vx;
    input.vy = output.vy;
    input.vz = output.vz;
    input.pad = 0;
    gte_gpf12(&input, factor, &output);
    particle->vel[0] = output.vx;
    particle->vel[1] = output.vy;
    particle->vel[2] = output.vz;
    emitter->prev_particles[idx] = *particle;
}

static sint32 effects_update_particles(CB_NODE *node)
{
    EFFECT_EMITTER *emitter = &effects_emitter;
    uint32 idx;

    FUNCTION_MARKER(0x8004199C, "MAIN.EXE");
    memcpy(emitter->prev_particles, emitter->particles, sizeof(emitter->particles));
    emitter->timer--;
    if (emitter->timer < 0)
    {
        for (idx = 0; idx < EFFECT_PARTICLE_COUNT && emitter->particles[idx].kind != 0; ++idx)
        {
        }
        if (idx == EFFECT_PARTICLE_COUNT)
            emitter->timer = 0;
        else
        {
            effects_create_particle(emitter, idx);
            emitter->timer = emitter->period;
        }
    }
    for (idx = 0; idx < EFFECT_PARTICLE_COUNT; ++idx)
    {
        EFFECT_PARTICLE *particle = &emitter->particles[idx];

        if (particle->kind != 0)
        {
            particle->pos[0] = particle->pos[0] + particle->vel[0];
            particle->pos[1] = particle->pos[1] + particle->vel[1];
            particle->pos[2] = particle->pos[2] + particle->vel[2];
            particle->vel[1] = particle->vel[1] - 2u;
            if (emitter->floor >= particle->pos[1])
                particle->kind = 0;
        }
    }
    return 0;
}

