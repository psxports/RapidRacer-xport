static sint32 sin28(uint32 index)
{
    uint32 half = index & 2047u;
    sint32 value = SIN28[half <= 1024u ? half : 2048u - half];
    return index & 2048u ? -value : value;
}

static uint64 quat_abs_s64_bits(uint64 val)
{
    if (val & (uint64)1 << 63)
        return ~val + 1;
    return val;
}

static void quat_mul_vals(QUAT *output, const QUAT *left, const QUAT *right)
{
    QUAT result;

    result.w = shr28(mul64(left->w, right->w) - mul64(left->x, right->x) - mul64(left->y, right->y) - mul64(left->z, right->z));
    result.x = shr28(mul64(left->w, right->x) + mul64(right->w, left->x) + mul64(left->y, right->z) - mul64(left->z, right->y));
    result.y = shr28(mul64(left->w, right->y) + mul64(right->w, left->y) + mul64(left->z, right->x) - mul64(left->x, right->z));
    result.z = shr28(mul64(left->w, right->z) + mul64(right->w, left->z) + mul64(left->x, right->y) - mul64(left->y, right->x));
    *output = result;
}

void quat_matrix(const QUAT *quat, MATRIX *matrix)
{
    sint32 x = quat->x >> 16;
    sint32 y = quat->y >> 16;
    sint32 z = quat->z >> 16;
    sint32 w = quat->w >> 16;
    sint32 xx2 = 2u * mul32(x, x);
    sint32 yy2 = 2u * mul32(y, y);
    sint32 zz2 = 2u * mul32(z, z);
    sint32 xy2 = 2u * mul32(x, y);
    sint32 xz2 = 2u * mul32(x, z);
    sint32 yz2 = 2u * mul32(y, z);
    sint32 wx2 = 2u * mul32(w, x);
    sint32 wy2 = 2u * mul32(w, y);
    sint32 wz2 = 2u * mul32(w, z);

    matrix->m[0][0] = sra(0x1000000 - zz2 - yy2, 12);
    matrix->m[1][1] = sra(0x1000000 - zz2 - xx2, 12);
    matrix->m[2][2] = sra(0x1000000 - yy2 - xx2, 12);
    matrix->m[1][0] = sra(xy2 + wz2, 12);
    matrix->m[0][1] = sra(xy2 - wz2, 12);
    matrix->m[2][0] = sra(xz2 - wy2, 12);
    matrix->m[0][2] = sra(xz2 + wy2, 12);
    matrix->m[2][1] = sra(yz2 + wx2, 12);
    matrix->m[1][2] = sra(yz2 - wx2, 12);
}

static void quat_angle_vals(uint32 angle, sint32 *s_ret, sint32 *c_ret)
{
    sint32 signed_angle = angle;
    sint32 rounded = signed_angle + (angle >> 31);
    uint32 half = (uint16)(rounded >> 1);
    uint32 table_offset = rounded >> 15 & 0x3FFC;
    sint32 c = sin28(table_offset / 4 + 1024 & 4095);
    sint32 s = sin28(table_offset / 4);
    sint32 delta = DELTA_Q28(half * half);
    sint32 scale = mul32(25736, half) >> 12;
    uint64 c_bits = mul64(c, delta) - mul64(scale, s);
    uint64 s_bits = mul64(scale, c) + mul64(s, delta);

    *c_ret = shr28(c_bits);
    *s_ret = shr28(s_bits);
}

sint32 quat_cos(uint32 angle)
{
    sint32 signed_angle = angle;
    sint32 rounded = signed_angle + (angle >> 31);
    uint32 half = (uint16)(rounded >> 1);
    uint32 table_offset = rounded >> 15 & 0x3FFC;
    sint32 c = sin28(table_offset / 4 + 1024 & 4095);
    uint32 delta = DELTA_Q28(half * half);
    sint32 scale = mul32(25736, half) >> 12;
    sint32 s = sin28(table_offset / 4);

    return shr28(mul64(c, delta) - mul64(scale, s));
}

sint32 quat_sin(uint32 angle)
{
    sint32 signed_angle = angle;
    sint32 rounded = signed_angle + (angle >> 31);
    uint32 half = (uint16)(rounded >> 1);
    uint32 table_offset = rounded >> 15 & 0x3FFC;
    sint32 c = sin28(table_offset / 4 + 1024 & 4095);
    uint32 delta = DELTA_Q28(half * half);
    sint32 scale = mul32(25736, half) >> 12;
    sint32 s = sin28(table_offset / 4);

    return shr28(mul64(scale, c) + mul64(s, delta));
}

QUAT *quat_mul(QUAT *output, const QUAT *right)
{
    FUNCTION_MARKER(0x8001298C, "MAIN.EXE");
    quat_mul_vals(output, output, right);
    return output;
}

static QUAT *quat_premul(QUAT *output, const QUAT *left)
{
    FUNCTION_MARKER(0x80012C90, "MAIN.EXE");
    quat_mul_vals(output, left, output);
    return output;
}

