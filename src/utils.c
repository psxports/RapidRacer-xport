QUAT *quat_from_angles(QUAT *output, const VEC3 *angles)
{
    QUAT tmp;
    sint32 s;
    sint32 c;

    FUNCTION_MARKER(0x800131AC, "MAIN.EXE");
    quat_angle_vals(angles->x, &s, &c);
    output->x = s;
    output->y = output->z = 0;
    output->w = c;
    quat_angle_vals(angles->y, &s, &c);
    tmp.x = tmp.z = 0;
    tmp.y = s;
    tmp.w = c;
    quat_mul(output, &tmp);
    quat_angle_vals(angles->z, &s, &c);
    tmp.x = tmp.y = 0;
    tmp.z = s;
    tmp.w = c;
    quat_mul(output, &tmp);
    return output;
}

QUAT *quat_from_axis_angle(QUAT *output, uint32 angle)
{
    sint32 s;
    sint32 c;

    FUNCTION_MARKER(0x80013B10, "MAIN.EXE");
    quat_angle_vals(angle, &s, &c);
    output->x = output->y = 0;
    output->z = s;
    output->w = c;
    return output;
}

