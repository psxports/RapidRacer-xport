uint32 swap32(uint32 val)
{
    return val >> 24 | val >> 8 & 0x0000FF00 | val << 8 & 0x00FF0000 | val << 24;
}

sint32 abs_max3(sint32 x, sint32 y, sint32 z)
{
    sint32 max_abs = abs(x);
    sint32 abs_y = abs(y);
    sint32 abs_z = abs(z);

    if (max_abs < abs_y)
        max_abs = abs_y;
    if (max_abs < abs_z)
        max_abs = abs_z;
    return max_abs;
}

sint32 vec_dist_sq(const VEC3 *v0, const VEC3 *v1)
{
    VECTOR input;
    VECTOR sq;

    FUNCTION_MARKER(0x8002CF14, "MAIN.EXE");
    input.vx = v0->x - v1->x;
    input.vy = v0->y - v1->y;
    input.vz = v0->z - v1->z;
    input.pad = 0;
    Square0(&input, &sq);
    return sq.vx + sq.vy + sq.vz;
}

sint32 vec_normalize(const VEC3 *input, SVECTOR *output)
{
    VECTOR src;
    src.vx = input->x;
    src.vy = input->y;
    src.vz = input->z;
    src.pad = 0;
    sint32 shift;

    FUNCTION_MARKER(0x80032C40, "MAIN.EXE");
    shift = 18 - Lzc(abs_max3(src.vx, src.vy, src.vz));
    if (shift > 0)
    {
        src.vx >>= shift;
        src.vy >>= shift;
        src.vz >>= shift;
    }
    return VectorNormalS(&src, output);
}

